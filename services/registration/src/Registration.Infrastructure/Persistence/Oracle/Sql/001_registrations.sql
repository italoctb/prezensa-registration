CREATE TABLE REGISTRATIONS (
    ID VARCHAR2(36 CHAR) NOT NULL,
    SOURCE_DRAFT_ID VARCHAR2(36 CHAR) NOT NULL,
    CPF CHAR(11 CHAR) NOT NULL,
    APPLICANT_JSON CLOB NOT NULL,
    STATUS VARCHAR2(20 CHAR) NOT NULL,
    FRAUD_STATUS VARCHAR2(20 CHAR) NOT NULL,
    FAILURE_REASON VARCHAR2(512 CHAR),
    CREATED_AT_TICKS NUMBER(19) NOT NULL,
    UPDATED_AT_TICKS NUMBER(19) NOT NULL,
    APPROVED_AT_TICKS NUMBER(19),
    APPROVED_BY VARCHAR2(256 CHAR),
    VERSION NUMBER(19) NOT NULL,
    CONSTRAINT PK_REGISTRATIONS PRIMARY KEY (ID),
    CONSTRAINT UX_REGISTRATIONS_DRAFT UNIQUE (SOURCE_DRAFT_ID),
    CONSTRAINT UX_REGISTRATIONS_CPF UNIQUE (CPF),
    CONSTRAINT CK_REGISTRATIONS_STATUS CHECK (STATUS IN ('Received', 'Processing', 'Completed', 'Rejected', 'Failed', 'Cancelled')),
    CONSTRAINT CK_REGISTRATIONS_FRAUD CHECK (FRAUD_STATUS IN ('NotRequested', 'Pending', 'Approved', 'Rejected')),
    CONSTRAINT CK_REGISTRATIONS_VERSION CHECK (VERSION >= 1),
    CONSTRAINT CK_REGISTRATIONS_TIME CHECK (UPDATED_AT_TICKS >= CREATED_AT_TICKS),
    CONSTRAINT CK_REGISTRATIONS_APPROVAL CHECK (
        (STATUS = 'Completed' AND APPROVED_AT_TICKS IS NOT NULL AND APPROVED_BY IS NOT NULL)
        OR (STATUS <> 'Completed' AND APPROVED_AT_TICKS IS NULL AND APPROVED_BY IS NULL)
    ),
    CONSTRAINT CK_REGISTRATIONS_FAILURE CHECK (
        (STATUS = 'Failed' AND FAILURE_REASON IS NOT NULL)
        OR (STATUS <> 'Failed' AND FAILURE_REASON IS NULL)
    )
)
